import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
await mkdir('.qa', {recursive:true});
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
await page.goto('http://127.0.0.1:4173/',{waitUntil:'domcontentloaded',timeout:60000});
await page.locator('h1').waitFor({timeout:120000});
await page.evaluate(() => document.fonts.ready);
await page.screenshot({path:'.qa/desktop-top.png'});
await page.locator('#work').scrollIntoViewIfNeeded();
await page.waitForTimeout(700);
await page.screenshot({path:'.qa/desktop-work.png'});
await page.locator('#about').scrollIntoViewIfNeeded();
await page.waitForTimeout(700);
await page.screenshot({path:'.qa/desktop-about.png'});
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:4173/',{waitUntil:'domcontentloaded',timeout:60000});
await page.locator('h1').waitFor();
await page.screenshot({path:'.qa/mobile-top.png',fullPage:false});
console.log(JSON.stringify({title:await page.title(),horizontalOverflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),missingImages:await page.locator('img').evaluateAll(imgs=>imgs.filter(i=>i.complete&&i.naturalWidth===0).map(i=>i.src))}));
await browser.close();
